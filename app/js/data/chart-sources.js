/* Worldwide chart source registry.
 *
 * One record per national (or regional) aeronautical information publisher.
 * A record is a *pointer to the authority*, never a chart copy: Stratos does
 * not scrape these portals, and a public web page is not a redistribution
 * licence. `licence` follows the six categories below, and `checked` is the
 * date Stratos last confirmed the licence position. A null `checked` means the
 * terms have NOT been established, and the interface says so.
 *
 * Rules for editing this file:
 *   1. `url` is the publisher's own portal, never a mirror or an aggregator.
 *   2. Never move a record to FREE_REUSE without written terms that name
 *      third-party display and redistribution.
 *   3. `icao` holds the ICAO location-indicator prefixes the authority governs.
 *   4. A country with no record is not hidden: the resolver reports that no
 *      source is listed, which is the honest answer.
 */

